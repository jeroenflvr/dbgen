import asyncio
import duckdb
import os
import sys
import logging
import argparse
from concurrent.futures import ProcessPoolExecutor

log_file_path = "parts_gen.log"
created_tables = []


def setup_logging():

    logger = logging.getLogger()
    logger.setLevel(logging.INFO)

    formatter = logging.Formatter("%(asctime)s [%(levelname)s] %(message)s")

    console_handler = logging.StreamHandler(sys.stdout)
    console_handler.setLevel(logging.INFO)
    console_handler.setFormatter(formatter)
    logger.addHandler(console_handler)

    file_handler = logging.FileHandler(log_file_path)
    file_handler.setLevel(logging.INFO)
    file_handler.setFormatter(formatter)
    logger.addHandler(file_handler)


def check_or_create_table_dir(table: str, root: str) -> None:
    if not table in created_tables:
        os.makedirs(os.path.join(root, table), exist_ok=True)
        created_tables.append(table)


def get_existing_tables(conn: duckdb.DuckDBPyConnection) -> set[duckdb.table]:
    """
    Retrieves the names of existing tables in the DuckDB database connection.

    Args:
        conn (duckdb.DuckDBPyConnection): The DuckDB database connection object.

    Returns:
        set[duckdb.table]: A set containing the names of the existing tables in the database.
                           If an error occurs, an empty set is returned.

    Raises:
        None: All exceptions are caught and logged.
    """

    try:
        result = conn.execute("SHOW TABLES").fetchall()
        tables = {row[0] for row in result}
        return tables
    except Exception as e:
        logging.error(f"Error fetching tables: {e}")
        return set()


def export_tables_to_parquet(conn: duckdb.DuckDBPyConnection,
            tables: set[duckdb.table],
            step: int,
            output_path: str):
    """
    Exports a set of DuckDB tables to Parquet files.

    Args:
        conn (duckdb.DuckDBPyConnection): The DuckDB connection object.
        tables (set[duckdb.table]): A set of DuckDB tables to be exported.
        step (int): The step number to be included in the Parquet file name.
        output_path (str): The directory path where the Parquet files will be saved.

    Raises:
        Exception: If exporting any table fails, an error message is logged.
    """
    
    for table in tables:
        check_or_create_table_dir(table, output_path)
        parquet_file = os.path.join(
            output_path, table, f"{table}_{str(step).zfill(7)}.parquet"
        )

        try:
            logging.info(f"Exporting table '{table}' to '{parquet_file}'...")
            conn.execute(f"COPY {table} TO '{parquet_file}' (FORMAT 'parquet')")
            logging.info(f"Successfully exported '{table}' to '{parquet_file}'.")
        except Exception as e:
            logging.error(f"Failed to export table '{table}': {e}")


